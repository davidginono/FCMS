-- One company-owned general ledger. Operational FCMS registers are subsidiary records.
create table gl_books (
 id boolean primary key default true check(id), opening_date date not null,
 policy_reference varchar(200) not null check(length(trim(policy_reference))>0),
 opening_mode varchar(10) not null check(opening_mode in ('ZERO','JOURNAL')),
 state varchar(12) not null check(state in ('PENDING','APPROVED')), version bigint not null default 0,
 maker_id bigint not null references users(id), checker_id bigint references users(id),
 created_at timestamptz not null default current_timestamp, approved_at timestamptz,
 check(state<>'APPROVED' or (checker_id is not null and checker_id<>maker_id and approved_at is not null))
);
create table gl_accounts (
 id bigint generated by default as identity primary key, code varchar(6) not null unique check(code~'^[1-5][0-9]{5}$'),
 name varchar(160) not null check(length(trim(name))>0), description varchar(500) not null default '',
 classification varchar(12) not null check(classification in ('ASSET','LIABILITY','EQUITY','EXPENSE','INCOME')),
 normal_balance varchar(6) not null check(normal_balance in ('DEBIT','CREDIT')),
 depth integer not null check(depth between 1 and 4), parent_id bigint references gl_accounts(id),
 cash_account boolean not null default false, active boolean not null default true,
 version bigint not null default 0, created_by bigint references users(id),
 created_at timestamptz not null default current_timestamp,
 check((depth=1 and parent_id is null) or (depth>1 and parent_id is not null)),
 check(not cash_account or (classification='ASSET' and depth=4))
);
insert into gl_accounts(code,name,classification,normal_balance,depth) values
 ('100000','Assets','ASSET','DEBIT',1),('200000','Liabilities','LIABILITY','CREDIT',1),
 ('300000','Equity','EQUITY','CREDIT',1),('400000','Expenses','EXPENSE','DEBIT',1),('500000','Income','INCOME','CREDIT',1);
create table gl_periods (
 id bigint generated by default as identity primary key, name varchar(100) not null,
 starts_on date not null, ends_on date not null check(ends_on>=starts_on),
 state varchar(10) not null default 'OPEN' check(state in ('OPEN','CLOSED')),
 created_by bigint not null references users(id), closed_by bigint references users(id),
 close_reason varchar(500), closed_at timestamptz, version bigint not null default 0,
 exclude using gist(daterange(starts_on,ends_on,'[]') with &&)
);
create table gl_journals (
 id bigint generated by default as identity primary key,
 kind varchar(12) not null check(kind in ('JOURNAL','RECEIPT','PAYMENT','OPENING','REVERSAL')),
 reference varchar(100) not null, description varchar(1000) not null,
 evidence_reference varchar(200) not null check(length(trim(evidence_reference))>0),
 effective_date date not null, period_id bigint not null references gl_periods(id),
 cash_flow varchar(12) not null check(cash_flow in ('NONE','OPERATING','INVESTING','FINANCING','INTERNAL')),
 state varchar(12) not null check(state in ('DRAFT','SUBMITTED','REJECTED','POSTED','CANCELLED')),
 maker_id bigint not null references users(id), checker_id bigint references users(id),
 request_key uuid not null, payload_hash varchar(64) not null, version bigint not null default 0,
 reverses_id bigint unique references gl_journals(id), review_comment varchar(500) not null default '',
 created_at timestamptz not null default current_timestamp, posted_at timestamptz,
 unique(maker_id,request_key), check(checker_id is null or checker_id<>maker_id),
 check(state<>'POSTED' or (checker_id is not null and posted_at is not null and length(trim(review_comment))>0)),
 check((kind='REVERSAL')=(reverses_id is not null))
);
create unique index gl_one_opening on gl_journals(kind) where kind='OPENING' and state not in ('REJECTED','CANCELLED');
create index gl_journal_posted_date on gl_journals(effective_date,id) where state='POSTED';
create table gl_lines (
 id bigint generated by default as identity primary key, journal_id bigint not null references gl_journals(id),
 line_number integer not null check(line_number between 1 and 50), account_id bigint not null references gl_accounts(id),
 account_code varchar(6) not null, account_name varchar(160) not null,
 debit numeric not null check(debit>=0 and debit<1000000000000 and scale(debit)<=2),
 credit numeric not null check(credit>=0 and credit<1000000000000 and scale(credit)<=2),
 description varchar(500) not null default '', unique(journal_id,line_number),
 check((debit>0 and credit=0) or (credit>0 and debit=0))
);
create index gl_lines_account_journal on gl_lines(account_id,journal_id);
create table gl_source_links (
 source_kind varchar(30) not null, source_id bigint not null,
 journal_id bigint not null unique references gl_journals(id), evidence_reference varchar(200) not null,
 linked_by bigint not null references users(id), linked_at timestamptz not null default current_timestamp,
 primary key(source_kind,source_id)
);
create function fcms_gl_account_guard() returns trigger language plpgsql as $$
declare p gl_accounts;
begin
 if TG_OP='DELETE' then raise exception 'Deactivate accounts; history cannot be deleted' using errcode='23514'; end if;
 if TG_OP='UPDATE' then
  if row(new.code,new.classification,new.normal_balance,new.depth,new.parent_id,new.cash_account)
     is distinct from row(old.code,old.classification,old.normal_balance,old.depth,old.parent_id,old.cash_account)
  then raise exception 'Account identity and classification are immutable' using errcode='23514'; end if;
  if old.depth=1 and not new.active then raise exception 'Main groups remain active' using errcode='23514'; end if;
 end if;
 if new.parent_id is not null then
  select * into p from gl_accounts where id=new.parent_id for share;
  if p.id is null or p.depth<>new.depth-1 or p.classification<>new.classification or (new.active and not p.active)
  then raise exception 'Invalid account hierarchy' using errcode='23514'; end if;
 end if;
 if not new.active and exists(select 1 from gl_accounts where parent_id=new.id and active)
 then raise exception 'Active child accounts remain' using errcode='23514'; end if;
 return new;
end; $$;
create trigger gl_account_guard before insert or update or delete on gl_accounts for each row execute function fcms_gl_account_guard();
create function fcms_gl_period_guard() returns trigger language plpgsql as $$
begin
 if TG_OP='DELETE' then raise exception 'Periods cannot be deleted' using errcode='23514'; end if;
 if row(new.starts_on,new.ends_on,new.created_by) is distinct from row(old.starts_on,old.ends_on,old.created_by)
 then raise exception 'Period dates are immutable' using errcode='23514'; end if;
 if new.state='CLOSED' and exists(select 1 from gl_journals where period_id=new.id and state in ('DRAFT','SUBMITTED'))
 then raise exception 'Unresolved journals prevent closing' using errcode='23514'; end if;
 return new;
end; $$;
create trigger gl_period_guard before update or delete on gl_periods for each row execute function fcms_gl_period_guard();
create function fcms_gl_journal_guard() returns trigger language plpgsql as $$
begin
 if TG_OP='DELETE' or old.state in ('POSTED','CANCELLED') then raise exception 'Posted accounting history is immutable' using errcode='23514'; end if;
 if row(new.maker_id,new.request_key,new.reverses_id,new.kind) is distinct from row(old.maker_id,old.request_key,old.reverses_id,old.kind)
 then raise exception 'Journal identity is immutable' using errcode='23514'; end if;
 if old.state='SUBMITTED' and row(new.reference,new.description,new.evidence_reference,new.effective_date,new.period_id,new.cash_flow,new.payload_hash) is distinct from row(old.reference,old.description,old.evidence_reference,old.effective_date,old.period_id,old.cash_flow,old.payload_hash) then raise exception 'Submitted journal payload is immutable' using errcode='23514'; end if;
 if old.state='SUBMITTED' and new.state not in ('REJECTED','POSTED') then raise exception 'Invalid review transition' using errcode='23514'; end if;
 if old.state in ('DRAFT','REJECTED') and new.state not in ('DRAFT','SUBMITTED','CANCELLED') then raise exception 'Submit before review' using errcode='23514'; end if;
 return new;
end; $$;
create trigger gl_journal_guard before update or delete on gl_journals for each row execute function fcms_gl_journal_guard();
create function fcms_gl_line_guard() returns trigger language plpgsql as $$
declare journal bigint; current_state text;
begin
 if TG_OP='UPDATE' and new.journal_id<>old.journal_id then raise exception 'Journal line identity is immutable' using errcode='23514'; end if;
 journal := case when TG_OP='DELETE' then old.journal_id else new.journal_id end;
 select state into current_state from gl_journals where id=journal for update;
 if current_state not in ('DRAFT','REJECTED') then raise exception 'Submitted lines are immutable' using errcode='23514'; end if;
 if TG_OP='DELETE' then return old; end if;
 return new;
end; $$;
create trigger gl_line_guard before insert or update or delete on gl_lines for each row execute function fcms_gl_line_guard();
create function fcms_gl_post_guard() returns trigger language plpgsql as $$
declare p gl_periods; b gl_books; cnt integer; difference numeric; cash_delta numeric; has_cash boolean; o gl_journals;
begin
 if new.state<>'POSTED' then return new; end if;
 select * into p from gl_periods where id=new.period_id for share;
 select * into b from gl_books where id=true;
 if p.state<>'OPEN' or new.effective_date not between p.starts_on and p.ends_on or b.state is distinct from 'APPROVED' or new.effective_date<b.opening_date
 then raise exception 'Approved books and open period are required' using errcode='23514'; end if;
 if new.kind='OPENING' then
  if b.opening_mode<>'JOURNAL' or new.effective_date<>b.opening_date or exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.id and a.classification in ('INCOME','EXPENSE'))
  then raise exception 'Invalid opening balance journal' using errcode='23514'; end if;
 elsif b.opening_mode='JOURNAL' and not exists(select 1 from gl_journals where kind='OPENING' and state='POSTED')
 then raise exception 'Reviewed opening journal is required' using errcode='23514'; end if;
 perform a.id from gl_accounts a where a.id in (select account_id from gl_lines where journal_id=new.id) order by a.id for share;
 if exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.id and (not a.active or a.depth<>4))
 then raise exception 'Active posting accounts are required' using errcode='23514'; end if;
 select count(*),sum(l.debit-l.credit),coalesce(sum(case when a.cash_account then l.debit-l.credit else 0 end),0),bool_or(a.cash_account)
 into cnt,difference,cash_delta,has_cash from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.id;
 if cnt not between 2 and 50 or difference<>0 then raise exception 'Balanced journal with 2 to 50 lines is required' using errcode='23514'; end if;
 if new.kind='RECEIPT' and cash_delta<=0 or new.kind='PAYMENT' and cash_delta>=0
 then raise exception 'Receipt/payment cash direction is invalid' using errcode='23514'; end if;
 if new.kind<>'OPENING' and ((cash_delta<>0 and new.cash_flow not in ('OPERATING','INVESTING','FINANCING')) or (cash_delta=0 and new.cash_flow<>case when has_cash then 'INTERNAL' else 'NONE' end))
 then raise exception 'Explicit cash-flow classification is required' using errcode='23514'; end if;
 if new.reverses_id is not null then
  select * into o from gl_journals where id=new.reverses_id for update;
  if o.state<>'POSTED' or o.kind in ('OPENING','REVERSAL') or new.maker_id=o.maker_id or new.checker_id=o.maker_id or new.effective_date<o.effective_date
  then raise exception 'Independent linked reversal is required' using errcode='23514'; end if;
  if exists((select account_id,debit,credit from gl_lines where journal_id=new.id) except all(select account_id,credit,debit from gl_lines where journal_id=o.id))
   or exists((select account_id,credit,debit from gl_lines where journal_id=o.id) except all(select account_id,debit,credit from gl_lines where journal_id=new.id))
  then raise exception 'Reversal must exactly swap original lines' using errcode='23514'; end if;
 end if;
 return new;
end; $$;
create trigger gl_post_guard before insert or update on gl_journals for each row execute function fcms_gl_post_guard();
