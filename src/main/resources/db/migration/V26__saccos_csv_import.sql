insert into claims(name) values ('client.import');
insert into role_claims(role_id,claim)
 select role_id,'client.import' from roles where lower(role_name)='admin';

create function fcms_saccos_import_total(payload jsonb,field_name text) returns numeric language sql immutable as $$
 select coalesce(sum(coalesce(nullif(item->'row'->'values'->>field_name,''),'0')::numeric),0)
 from jsonb_array_elements(payload) item
$$;

create table saccos_import_batches (
 id bigint generated by default as identity primary key,
 token uuid not null unique,
 owner_id bigint not null references users(id),
 request_key uuid not null,
 digest varchar(64) not null check (digest ~ '^[0-9a-f]{64}$'),
 state varchar(12) not null default 'DRAFT' check(state in ('DRAFT','COMMITTED','CANCELLED','EXPIRED')),
 row_count integer not null check(row_count between 1 and 100),
 total_annual_fee numeric(18,2) not null check(total_annual_fee>=0),
 total_paid numeric(18,2) not null check(total_paid>=0),
 payload jsonb not null check(jsonb_typeof(payload)='array' and octet_length(payload::text)<=1048576),
 created_at timestamptz not null default current_timestamp,
 expires_at timestamptz not null default (current_timestamp+interval '24 hours'),
 committed_at timestamptz,
 unique(owner_id,request_key),
 check(expires_at>created_at),
 check((state='COMMITTED')=(committed_at is not null)),
 check(jsonb_array_length(payload)=case when state in ('DRAFT','COMMITTED') then row_count else 0 end),
 check(state not in ('DRAFT','COMMITTED') or (total_annual_fee=fcms_saccos_import_total(payload,'annualFee')
  and total_paid=fcms_saccos_import_total(payload,'amount')))
);
create index saccos_import_owner_state_idx on saccos_import_batches(owner_id,state,expires_at);
create table saccos_import_clients (
 batch_id bigint not null references saccos_import_batches(id),
 ordinal integer not null check(ordinal between 1 and 100),
 client_id bigint not null unique references saccos(id),
 primary key(batch_id,ordinal)
);

create function fcms_saccos_import_guard() returns trigger language plpgsql as $$
begin
 if tg_op='DELETE' then raise exception 'Import evidence is retained' using errcode='23514'; end if;
 if old.state<>'DRAFT' or new.state not in ('COMMITTED','CANCELLED','EXPIRED')
  or row(new.token,new.owner_id,new.request_key,new.digest,new.row_count,new.total_annual_fee,new.total_paid,new.created_at,new.expires_at)
   is distinct from row(old.token,old.owner_id,old.request_key,old.digest,old.row_count,old.total_annual_fee,old.total_paid,old.created_at,old.expires_at)
  or (new.state='COMMITTED' and new.payload is distinct from old.payload)
  or (new.state='EXPIRED' and old.expires_at>current_timestamp) then
  raise exception 'Invalid import transition' using errcode='23514';
 end if;
 if new.state='COMMITTED' and (old.expires_at<=current_timestamp
  or (select count(*) from saccos_import_clients where batch_id=old.id)<>old.row_count) then
  raise exception 'Incomplete or expired import' using errcode='23514';
 end if;
 return new;
end; $$;
create trigger saccos_import_guard before update or delete on saccos_import_batches
 for each row execute function fcms_saccos_import_guard();
create function fcms_saccos_import_client_guard() returns trigger language plpgsql as $$
declare batch_state text; batch_count integer;
begin
 if tg_op<>'INSERT' then raise exception 'Import associations are immutable' using errcode='23514'; end if;
 select state,row_count into batch_state,batch_count from saccos_import_batches where id=new.batch_id for update;
 if batch_state is distinct from 'DRAFT' or new.ordinal>batch_count then
  raise exception 'Invalid import association' using errcode='23514';
 end if;
 return new;
end; $$;
create trigger saccos_import_client_guard before insert or update or delete on saccos_import_clients
 for each row execute function fcms_saccos_import_client_guard();
