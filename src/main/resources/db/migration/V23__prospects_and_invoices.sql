create function fcms_sales_items_total(items jsonb) returns numeric language plpgsql immutable as $$
declare item jsonb; total numeric := 0; description_bytes integer := 0;
begin
 if jsonb_typeof(items) is distinct from 'array' or jsonb_array_length(items) not between 1 and 50 then
  raise exception 'Invalid document items' using errcode='23514';
 end if;
 for item in select value from jsonb_array_elements(items) loop
  if jsonb_typeof(item->'description') is distinct from 'string'
   or length(btrim(item->>'description')) not between 1 and 4000
   or jsonb_typeof(item->'amount') is null or jsonb_typeof(item->'amount') not in ('number','string')
   or (item->>'amount') !~ '^(0|[1-9][0-9]{0,11})(\.[0-9]{1,2})?$' then
   raise exception 'Invalid document item' using errcode='23514';
  end if;
  description_bytes := description_bytes + octet_length(item->>'description') + 1;
  total := total + (item->>'amount')::numeric;
 end loop;
 if description_bytes > 50000 or total > 999999999999.99 then
  raise exception 'Document limit exceeded' using errcode='23514';
 end if;
 return total;
end; $$;
create table sales_documents (
 id bigint generated by default as identity primary key,
 kind varchar(12) not null check (kind in ('PROSPECT','INVOICE')),
 client_type varchar(20) not null check (client_type in ('SACCOS','AMCOS','UNION','MICROFINANCE','OTHER')),
 client_name varchar(150) not null check (length(btrim(client_name)) > 0),
 region varchar(100) not null default '', contact_name varchar(150) not null default '',
 phone varchar(40) not null default '', email varchar(190) not null default '',
 document_number varchar(60) not null check (length(btrim(document_number)) > 0),
 document_date date not null check (document_date >= date '1900-01-01'),
 valid_until date not null check (valid_until >= document_date),
 currency varchar(3) not null check (currency in ('TZS','USD','KES','EUR','GBP')),
 items jsonb not null,
 amount numeric(14,2) not null check (amount >= 0 and amount = fcms_sales_items_total(items)),
 terms varchar(2000) not null default '', billing_address varchar(250) not null default '',
 billing_city varchar(150) not null default '', billing_tin varchar(60) not null default '',
 payment_method varchar(16) not null check (payment_method in ('CASH','CHEQUE','BANK_TRANSFER')),
 version bigint not null default 0 check (version >= 0),
 created_by bigint not null references users(id), updated_by bigint not null references users(id),
 created_at timestamptz not null default current_timestamp,
 updated_at timestamptz not null default current_timestamp,
 unique(kind,document_number),
 check (kind <> 'PROSPECT' or client_type in ('SACCOS','AMCOS','UNION'))
);
create index sales_register_date_idx on sales_documents(kind,document_date,id);
create table sales_document_revisions (
 document_id bigint not null references sales_documents(id), version bigint not null,
 actor_id bigint not null references users(id), request_key uuid not null,
 fingerprint char(64) not null, snapshot jsonb not null,
 occurred_at timestamptz not null default current_timestamp,
 primary key(document_id,version), unique(actor_id,request_key)
);
create function fcms_sales_history_guard() returns trigger language plpgsql as $$
begin raise exception 'Sales document history is retained' using errcode='23514'; end; $$;
create trigger sales_revisions_guard before update or delete on sales_document_revisions
 for each row execute function fcms_sales_history_guard();
create trigger sales_documents_retention before delete on sales_documents
 for each row execute function fcms_sales_history_guard();
