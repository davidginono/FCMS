create unique index users_email_lower_uq on users (lower(email));

create index saccos_client_status_id_idx on saccos (client_status_id);
create index saccos_financial_year_id_idx on saccos (financial_year_id);
create index saccos_status_entry_id_idx on saccos (client_status_id, entry_date, id);

create index tasks_user_id_idx on tasks (user_id);
create index tasks_saccos_id_idx on tasks (saccos_id);
create index tasks_type_id_idx on tasks (task_type_id);
create index tasks_status_id_idx on tasks (task_status_id);
create index tasks_status_start_id_idx on tasks (task_status_id, start_date, id);

create index expenses_user_id_idx on expenses (user_id);
create index expenses_status_id_idx on expenses (status_id);
create index expenses_status_date_id_idx on expenses (status_id, date_created, id);

