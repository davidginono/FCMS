create table roles (
    role_id bigint generated by default as identity primary key,
    role_name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint roles_role_name_uq unique (role_name)
);

create table account_status (
    id bigint generated by default as identity primary key,
    status_name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint account_status_name_uq unique (status_name)
);

create table financial_year (
    id bigint generated by default as identity primary key,
    fyear varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint financial_year_fyear_uq unique (fyear)
);

create table client_status (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint client_status_name_uq unique (name)
);

create table task_types (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint task_types_name_uq unique (name)
);

create table task_status (
    id bigint generated by default as identity primary key,
    status_name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint task_status_name_uq unique (status_name)
);

create table expense_status (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    constraint expense_status_name_uq unique (name)
);

create table users (
    id bigint generated by default as identity primary key,
    first_name varchar(100) not null,
    last_name varchar(100) not null,
    email varchar(100) not null,
    leave_email varchar(100),
    image_path varchar(255),
    password varchar(255) not null,
    status_id bigint not null,
    role_id bigint not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    reset_token varchar(255),
    token_expiry timestamp(6) with time zone,
    otp varchar(255),
    otp_expiry timestamp(6) with time zone,
    constraint users_email_uq unique (email),
    constraint users_status_fk foreign key (status_id) references account_status (id),
    constraint users_role_fk foreign key (role_id) references roles (role_id)
);

create table saccos (
    id bigint generated by default as identity primary key,
    saccos_name varchar(255) not null,
    entry_date date not null default current_date,
    expire_date date,
    region varchar(255) not null,
    contract_file varchar(255),
    annual_fee numeric(14, 2) not null default 0,
    amount numeric(14, 2) not null default 0,
    system_install_fee numeric(14, 2) not null default 0,
    training_fee numeric(14, 2) not null default 0,
    android_fee numeric(14, 2) not null default 0,
    client_status_id bigint,
    financial_year_id bigint,
    created_at timestamp(6) with time zone not null default current_timestamp,
    updated_at timestamp(6) with time zone not null default current_timestamp,
    constraint saccos_client_status_fk foreign key (client_status_id) references client_status (id),
    constraint saccos_financial_year_fk foreign key (financial_year_id) references financial_year (id),
    constraint saccos_dates_ck check (expire_date is null or expire_date >= entry_date),
    constraint saccos_amounts_ck check (
        annual_fee >= 0
        and amount >= 0
        and system_install_fee >= 0
        and training_fee >= 0
        and android_fee >= 0
    )
);

create table tasks (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    saccos_id bigint not null,
    task_type_id bigint not null,
    task_status_id bigint not null,
    start_date date not null,
    end_date date not null,
    activities varchar(255),
    allowance numeric(14, 2) not null default 0,
    amount numeric(14, 2) not null default 0,
    observation varchar(255),
    remarks varchar(255),
    created_date timestamp(6) with time zone not null default current_timestamp,
    constraint tasks_user_fk foreign key (user_id) references users (id),
    constraint tasks_saccos_fk foreign key (saccos_id) references saccos (id),
    constraint tasks_type_fk foreign key (task_type_id) references task_types (id),
    constraint tasks_status_fk foreign key (task_status_id) references task_status (id),
    constraint tasks_dates_ck check (end_date >= start_date),
    constraint tasks_amounts_ck check (allowance >= 0 and amount >= 0)
);

create table expenses (
    id bigint generated by default as identity primary key,
    date_created date not null default current_date,
    user_id bigint,
    category varchar(255) not null,
    description varchar(255) not null,
    payee varchar(255),
    amount numeric(14, 2) not null,
    financial_year varchar(255) not null,
    status_id bigint not null,
    created_at timestamp(6) with time zone not null default current_timestamp,
    updated_at timestamp(6) with time zone not null default current_timestamp,
    constraint expenses_user_fk foreign key (user_id) references users (id),
    constraint expenses_status_fk foreign key (status_id) references expense_status (id),
    constraint expenses_amount_ck check (amount >= 0)
);

create index users_status_id_idx on users (status_id);
