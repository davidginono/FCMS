-- Accounting-owned, reviewed revisions. No accounting treatment is inferred from legacy fees.
create table gl_posting_mappings (
 id bigint generated by default as identity primary key,
 source_event varchar(30) not null check(source_event in ('INCOME_IN','PETTY_IN','PETTY_OUT','CLOUD_IN','CLOUD_OUT','BULK_IN','BULK_OUT','EXPENSE_PAYMENT')),
 debit_account_id bigint not null references gl_accounts(id), credit_account_id bigint not null references gl_accounts(id),
 voucher_kind varchar(10) not null check(voucher_kind in ('JOURNAL','RECEIPT','PAYMENT')),
 cash_flow varchar(12) not null check(cash_flow in ('NONE','OPERATING','INVESTING','FINANCING','INTERNAL')),
 policy_reference varchar(200) not null check(length(trim(policy_reference))>0),
 state varchar(10) not null default 'PENDING' check(state in ('PENDING','APPROVED','REJECTED','CANCELLED','RETIRED')),
 maker_id bigint not null references users(id), checker_id bigint references users(id),
 request_key uuid not null, payload_hash varchar(64) not null, version bigint not null default 0,
 review_reason varchar(500) not null default '', created_at timestamptz not null default current_timestamp,
 reviewed_at timestamptz, retired_by bigint references users(id), retired_at timestamptz,
 unique(maker_id,request_key), check(debit_account_id<>credit_account_id),
 check((state='PENDING' and checker_id is null and reviewed_at is null and review_reason='') or
       (state<>'PENDING' and checker_id is not null and reviewed_at is not null and length(trim(review_reason))>0)),
 check(state not in ('APPROVED','REJECTED','RETIRED') or checker_id<>maker_id),
 check((state='RETIRED' and retired_by is not null and retired_at is not null) or (state<>'RETIRED' and retired_by is null and retired_at is null))
);
create unique index gl_mapping_current_event on gl_posting_mappings(source_event) where state='APPROVED';
create function fcms_gl_mapping_guard() returns trigger language plpgsql as $$
declare d gl_accounts; c gl_accounts; delta integer; has_cash boolean;
begin
 if TG_OP='DELETE' then raise exception 'Posting mappings are retained as accounting evidence' using errcode='23514'; end if;
 if TG_OP='INSERT' then
  if new.state<>'PENDING' or new.version<>0 then raise exception 'Mappings start pending independent review' using errcode='23514'; end if;
 else
  if row(new.source_event,new.debit_account_id,new.credit_account_id,new.voucher_kind,new.cash_flow,new.policy_reference,new.maker_id,new.request_key,new.payload_hash,new.created_at)
   is distinct from row(old.source_event,old.debit_account_id,old.credit_account_id,old.voucher_kind,old.cash_flow,old.policy_reference,old.maker_id,old.request_key,old.payload_hash,old.created_at)
  then raise exception 'Mapping revisions are immutable' using errcode='23514'; end if;
  if new.version<>old.version+1 then raise exception 'Mapping version must advance once' using errcode='23514'; end if;
  if old.state='PENDING' then
   if new.state not in ('APPROVED','REJECTED','CANCELLED') or (new.state='CANCELLED' and new.checker_id<>new.maker_id)
   then raise exception 'Invalid mapping review transition' using errcode='23514'; end if;
  elsif old.state='APPROVED' then
   if new.state<>'RETIRED' or row(new.checker_id,new.review_reason,new.reviewed_at) is distinct from row(old.checker_id,old.review_reason,old.reviewed_at)
   then raise exception 'An approved mapping can only be retired with its evidence retained' using errcode='23514'; end if;
  else raise exception 'Reviewed mapping history is immutable' using errcode='23514';
  end if;
 end if;
 if TG_OP='INSERT' or new.state='APPROVED' then
  -- Consistent account lock order matches voucher posting.
  perform id from gl_accounts where id in (new.debit_account_id,new.credit_account_id) order by id for share;
  select * into d from gl_accounts where id=new.debit_account_id;
  select * into c from gl_accounts where id=new.credit_account_id;
  if d.id is null or c.id is null or not d.active or not c.active or d.depth<>4 or c.depth<>4
  then raise exception 'Active posting accounts are required' using errcode='23514'; end if;
  delta := (case when d.cash_account then 1 else 0 end)-(case when c.cash_account then 1 else 0 end);
  has_cash := d.cash_account or c.cash_account;
  if (new.voucher_kind='RECEIPT' and delta<=0) or (new.voucher_kind='PAYMENT' and delta>=0)
  then raise exception 'Voucher cash direction does not match the accounts' using errcode='23514'; end if;
  if (delta<>0 and new.cash_flow not in ('OPERATING','INVESTING','FINANCING')) or
   (delta=0 and new.cash_flow<>case when has_cash then 'INTERNAL' else 'NONE' end)
  then raise exception 'Cash-flow classification must match the account pair' using errcode='23514'; end if;
 end if;
 return new;
end; $$;
create trigger gl_mapping_guard before insert or update or delete on gl_posting_mappings for each row execute function fcms_gl_mapping_guard();
