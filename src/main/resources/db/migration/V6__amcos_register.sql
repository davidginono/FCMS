create table amcos (
    id bigint generated by default as identity primary key,
    client_name varchar(255) not null,
    entry_date date not null default current_date,
    expire_date date,
    region varchar(255) not null,
    contract_file varchar(255),
    annual_fee numeric(14, 2) not null default 0,
    amount numeric(14, 2) not null default 0,
    withholding_tax numeric(14, 2) not null default 0,
    commission numeric(14, 2) not null default 0,
    programmer_cost numeric(14, 2) not null default 0,
    system_install_fee numeric(14, 2) not null default 0,
    training_fee numeric(14, 2) not null default 0,
    android_fee numeric(14, 2) not null default 0,
    system_reinstall_fee numeric(14, 2) not null default 0,
    bulk_sms_fee numeric(14, 2) not null default 0,
    hosting_fee numeric(14, 2) not null default 0,
    client_status_id bigint,
    financial_year_id bigint,
    visible boolean not null default true,
    created_at timestamp(6) with time zone not null default current_timestamp,
    updated_at timestamp(6) with time zone not null default current_timestamp,
    constraint amcos_client_status_fk foreign key (client_status_id) references client_status (id),
    constraint amcos_financial_year_fk foreign key (financial_year_id) references financial_year (id),
    constraint amcos_dates_ck check (expire_date is null or expire_date >= entry_date),
    constraint amcos_amounts_ck check (
        annual_fee >= 0
        and amount >= 0
        and withholding_tax >= 0
        and commission >= 0
        and programmer_cost >= 0
        and system_install_fee >= 0
        and training_fee >= 0
        and android_fee >= 0
        and system_reinstall_fee >= 0
        and bulk_sms_fee >= 0
        and hosting_fee >= 0
    )
);


create index amcos_visible_year_name_idx on amcos(financial_year_id,client_name,id) where visible;
