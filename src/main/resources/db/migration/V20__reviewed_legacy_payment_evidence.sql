-- Retain only legacy payments whose effective date was absent at this upgrade.
create table expense_legacy_payment_candidates (
 expense_id bigint primary key references expenses(id), observed_at timestamptz not null default clock_timestamp()
);
insert into expense_legacy_payment_candidates(expense_id)
 select e.id from expenses e join expense_status s on s.id=e.status_id where e.paid_on is null and e.amount>0 and s.name in ('paid','reversed');
create trigger expense_legacy_candidates_retained before insert or update or delete on expense_legacy_payment_candidates for each row execute function fcms_gl_evidence_guard();
create table expense_payment_evidence (
 id bigint generated by default as identity primary key,
 expense_id bigint not null references expense_legacy_payment_candidates(expense_id),
 paid_on date not null, payer_id bigint not null references users(id),
 payment_reference varchar(100) not null check(length(trim(payment_reference))>0),
 document_reference varchar(200) not null check(length(trim(document_reference))>0),
 explanation varchar(1000) not null check(length(trim(explanation))>0),
 opening_policy_reference varchar(200) not null default '',
 state varchar(20) not null default 'PENDING' check(state in ('PENDING','APPROVED','REJECTED','CANCELLED')),
 maker_id bigint not null references users(id),created_at timestamptz not null default clock_timestamp(),
 request_key uuid not null,payload_hash varchar(64) not null,
 checker_id bigint references users(id),review_comment varchar(1000) not null default '',reviewed_at timestamptz,version bigint not null default 0,
 unique(maker_id,request_key),
 check((state='PENDING' and checker_id is null and reviewed_at is null) or (state<>'PENDING' and checker_id is not null and reviewed_at is not null and length(trim(review_comment))>0))
);
create unique index expense_evidence_current on expense_payment_evidence(expense_id) where state in ('PENDING','APPROVED');
create index expense_evidence_history on expense_payment_evidence(expense_id,id desc);
insert into claims(name) values ('expense.evidence.write'),('expense.evidence.review');
insert into role_claims select role_id,c.name from roles cross join claims c where lower(role_name)='admin' and c.name in ('expense.evidence.write','expense.evidence.review');
create function fcms_expense_payment_evidence_guard() returns trigger language plpgsql as $$
declare e expenses; status_name text; cutover finance_gl_cutover;
begin
 if TG_OP='DELETE' then raise exception 'Historical payment evidence is retained' using errcode='23514'; end if;
 select * into e from expenses where id=new.expense_id for update;
 select name into status_name from expense_status where id=e.status_id;
 if e.id is null or e.paid_on is not null or status_name not in ('paid','reversed')
  then raise exception 'Only unresolved legacy payments can receive evidence' using errcode='23514'; end if;
 if new.paid_on<e.date_created or new.paid_on>(clock_timestamp() at time zone 'Africa/Dar_es_Salaam')::date
  or (e.paid_at is not null and new.paid_on<>(e.paid_at at time zone 'Africa/Dar_es_Salaam')::date)
  or (e.paid_by is not null and new.payer_id<>e.paid_by)
  or (length(trim(e.payment_reference))>0 and new.payment_reference<>e.payment_reference)
  or exists(select 1 from expense_reversals r where r.expense_id=e.id and new.paid_on>(r.created_at at time zone 'Africa/Dar_es_Salaam')::date)
 then raise exception 'Historical payment evidence conflicts with retained facts' using errcode='23514'; end if;
 if TG_OP='INSERT' then
  new.created_at:=clock_timestamp();
  if new.state<>'PENDING' or new.version<>0 then raise exception 'Evidence starts pending review' using errcode='23514'; end if;
 else
  new.reviewed_at:=clock_timestamp();
  if old.state<>'PENDING' or new.state not in ('APPROVED','REJECTED','CANCELLED') or new.version<>old.version+1
   or row(new.id,new.expense_id,new.paid_on,new.payer_id,new.payment_reference,new.document_reference,new.explanation,new.opening_policy_reference,new.maker_id,new.created_at,new.request_key,new.payload_hash)
      is distinct from row(old.id,old.expense_id,old.paid_on,old.payer_id,old.payment_reference,old.document_reference,old.explanation,old.opening_policy_reference,old.maker_id,old.created_at,old.request_key,old.payload_hash)
  then raise exception 'Retained evidence can only receive one review' using errcode='23514'; end if;
  if new.state='CANCELLED' then
   if new.checker_id<>new.maker_id then raise exception 'Only the maker cancels evidence' using errcode='23514'; end if;
  elsif new.checker_id in (new.maker_id,new.payer_id,e.user_id) then
   raise exception 'Independent historical payment review is required' using errcode='23514';
  end if;
  if new.state='APPROVED' then
   perform pg_advisory_xact_lock_shared(hashtextextended('FCMS_FINANCE_CUTOVER',0));
   perform fcms_finance_require_open_date(new.paid_on);
   select * into cutover from finance_gl_cutover where id=true;
   if cutover.id is not null and new.paid_on<cutover.starts_on and new.opening_policy_reference<>cutover.policy_reference
    then raise exception 'Reviewed opening policy reference is required' using errcode='23514'; end if;
   if length(trim(new.opening_policy_reference))>0 and (cutover.id is null or new.paid_on>=cutover.starts_on or new.opening_policy_reference<>cutover.policy_reference)
    then raise exception 'Opening coverage must match the actual reviewed cutover' using errcode='23514'; end if;
  end if;
 end if;
 return new;
end; $$;
create trigger expense_payment_evidence_guard before insert or update or delete on expense_payment_evidence for each row execute function fcms_expense_payment_evidence_guard();

-- The verification timestamp remains distinct from the historical effective date.
-- Explicit independently reviewed opening treatment is an additional public contract fact.
create or replace view finance_gl_sources as
 select 'LEDGER_'||e.kind source_kind,e.id source_id,e.kind||case when e.amount_delta>0 then '_IN' else '_OUT' end source_event,
 e.transaction_date source_date,e.reference,e.description,e.amount_delta signed_amount,e.actor_id,
 case when exists(select 1 from ledger_entries r where r.reversal_of=e.id) then 'REVERSED' else 'ACTIVE' end source_state,
 case when e.reversal_of is null then null else 'LEDGER_'||e.kind end reverses_kind,e.reversal_of reverses_id,e.created_at recorded_at,false opening_verified
 from ledger_entries e where e.amount_delta<>0
 union all
 select 'EXPENSE',e.id,'EXPENSE_PAYMENT',coalesce(e.paid_on,h.paid_on),
 case when length(trim(e.payment_reference))>0 then e.payment_reference else coalesce(h.payment_reference,'') end,e.description,e.amount,coalesce(e.paid_by,h.payer_id,e.user_id),
 case when coalesce(e.paid_on,h.paid_on) is null then 'UNVERIFIED' when s.name='reversed' then 'REVERSED' else 'ACTIVE' end,null::text,null::bigint,coalesce(e.paid_at,h.reviewed_at),
 coalesce(h.opening_policy_reference<>'' and h.opening_policy_reference=c.policy_reference and h.paid_on<c.starts_on,false)
 from expenses e join expense_status s on s.id=e.status_id
 left join expense_payment_evidence h on h.expense_id=e.id and h.state='APPROVED'
 left join finance_gl_cutover c on c.id=true where e.amount>0 and s.name in ('paid','reversed')
 union all
 select 'EXPENSE_REVERSAL',r.id,'EXPENSE_REVERSAL',(r.created_at at time zone 'Africa/Dar_es_Salaam')::date,
 'EXP-REV-'||e.id,r.reason,-e.amount,r.actor_id,'ACTIVE','EXPENSE',e.id,r.created_at,false
 from expense_reversals r join expenses e on e.id=r.expense_id where e.amount>0;

create or replace view gl_source_coverage as
 select s.source_kind,s.source_id,s.source_date,abs(s.signed_amount) amount,
 case when b.state is distinct from 'APPROVED' or (b.opening_mode='JOURNAL' and not exists(select 1 from gl_journals where kind='OPENING' and state='POSTED')) then 'BOOKS_PENDING'
 when s.source_date is null or (s.reverses_id is not null and o.source_date is null)
  or (s.source_date<b.opening_date and (s.recorded_at is null or s.recorded_at>b.approved_at) and not s.opening_verified)
  or (o.source_date<b.opening_date and (o.recorded_at is null or o.recorded_at>b.approved_at) and not o.opening_verified) then 'UNVERIFIED'
 when s.source_date<b.opening_date then 'OPENING_COVERED'
 when j.state='POSTED' then 'POSTED' else 'UNPOSTED' end coverage
 from finance_gl_sources s left join finance_gl_sources o on o.source_kind=s.reverses_kind and o.source_id=s.reverses_id
 left join gl_books b on true
 left join gl_source_reservations r on r.source_kind=s.source_kind and r.source_id=s.source_id
 left join gl_journals j on j.id=r.journal_id;


create or replace function fcms_gl_source_assert(journal bigint,posting boolean,checker bigint) returns void language plpgsql as $$
declare l gl_source_links; s finance_gl_sources; o finance_gl_sources; j gl_journals;
 b gl_books; m gl_posting_mappings; original_journal bigint; event_name text; line_count integer;
begin
 select * into l from gl_source_links where journal_id=journal;
 if not found then return; end if;
 select * into j from gl_journals where id=journal;
 select * into s from finance_gl_sources where source_kind=l.source_kind and source_id=l.source_id;
 select * into b from gl_books where id=true;
 if s.source_id is null or s.source_date is null or s.source_state not in ('ACTIVE','REVERSED') or
  row(s.source_date,s.signed_amount) is distinct from row(l.source_date,l.signed_amount) or
  j.effective_date<>s.source_date or b.state is distinct from 'APPROVED' or s.source_date<b.opening_date or
  l.linked_by<>j.maker_id or l.evidence_reference<>j.evidence_reference
 then raise exception 'Verified source evidence does not match the voucher' using errcode='23514'; end if;
 if posting and (checker=s.actor_id or not exists(select 1 from gl_source_reservations r where r.source_kind=l.source_kind and r.source_id=l.source_id and r.journal_id=j.id))
 then raise exception 'Current preparation and independent source review are required' using errcode='23514'; end if;
 if (select coalesce(sum(debit),0) from gl_lines where journal_id=j.id)<>abs(s.signed_amount)
 then raise exception 'Voucher amount must equal the immutable source amount' using errcode='23514'; end if;
 event_name:=s.source_event;
 if s.reverses_id is not null then
  select * into o from finance_gl_sources where source_kind=s.reverses_kind and source_id=s.reverses_id;
  if o.source_date is null or o.signed_amount<>-s.signed_amount or o.source_state<>'REVERSED' or s.source_date<o.source_date or (posting and checker=o.actor_id)
  then raise exception 'Actual independent reversal evidence is required' using errcode='23514'; end if;
  if o.source_date<b.opening_date and (o.recorded_at is null or o.recorded_at>b.approved_at) and not o.opening_verified
  then raise exception 'Opening-covered source evidence requires verification' using errcode='23514'; end if;
  if o.source_date>=b.opening_date then
   select r.journal_id into original_journal from gl_source_reservations r join gl_journals v on v.id=r.journal_id
    where r.source_kind=o.source_kind and r.source_id=o.source_id and v.state='POSTED';
   if original_journal is null or j.kind<>'REVERSAL' or j.reverses_id is distinct from original_journal
   then raise exception 'Post the original source before preparing its exact linked reversal' using errcode='23514'; end if;
   if l.mapping_id is distinct from (select mapping_id from gl_source_links where journal_id=original_journal)
   then raise exception 'Reversal retains the original mapping revision' using errcode='23514'; end if;
   return;
  end if;
  event_name:=(case when o.source_kind='EXPENSE' then 'EXPENSE' else substring(o.source_kind from 8) end)||'_OPENING_REVERSAL';
 end if;
 select * into m from gl_posting_mappings where id=l.mapping_id for share;
 if m.id is null or m.source_event<>event_name or m.state not in ('APPROVED','RETIRED') or
  (not posting and m.state<>'APPROVED') or j.kind<>m.voucher_kind or j.cash_flow<>m.cash_flow or j.reverses_id is not null
 then raise exception 'An explicitly approved matching revision is required' using errcode='23514'; end if;
 select count(*) into line_count from gl_lines where journal_id=j.id;
 if line_count<>2 or not exists(select 1 from gl_lines where journal_id=j.id and account_id=m.debit_account_id and debit=abs(s.signed_amount) and credit=0) or
  not exists(select 1 from gl_lines where journal_id=j.id and account_id=m.credit_account_id and credit=abs(s.signed_amount) and debit=0)
 then raise exception 'Prepared lines must match the reviewed account pair and source amount' using errcode='23514'; end if;
end; $$;
