-- Reporting metadata only. Posted journals, lines and balances remain immutable.
create table gl_equity_reporting (
 id bigint generated by default as identity primary key,
 kind varchar(10) not null check(kind in ('SETUP','JOURNAL')),
 target_id bigint not null check(target_id>=0),
 base_id bigint references gl_equity_reporting(id),
 payload jsonb not null check(jsonb_typeof(payload)='object'),
 reason varchar(500) not null check(length(btrim(reason))>0),
 maker_id bigint not null references users(id), checker_id bigint references users(id),
 request_key uuid not null, payload_hash varchar(64) not null check(payload_hash~'^[a-f0-9]{64}$'),
 state varchar(10) not null default 'PENDING' check(state in ('PENDING','APPROVED','REJECTED','CANCELLED','RETIRED')),
 version bigint not null default 0 check(version>=0),
 created_at timestamptz not null default current_timestamp, reviewed_at timestamptz,
 review_reason varchar(500) not null default '',
 retired_by bigint references users(id),retired_at timestamptz,replaced_by bigint references gl_equity_reporting(id),
 unique(maker_id,request_key),
 check((kind='SETUP' and target_id=0) or (kind='JOURNAL' and target_id>0)),
 check(base_id is null or base_id<id),check(replaced_by is null or replaced_by>id),
 check((state='PENDING' and checker_id is null and reviewed_at is null and review_reason='') or
 (state<>'PENDING' and checker_id is not null and reviewed_at is not null and length(btrim(review_reason))>0)),
 check(state not in ('APPROVED','REJECTED','RETIRED') or checker_id<>maker_id),
 check(state<>'CANCELLED' or checker_id=maker_id),
 check((state='RETIRED' and retired_by is not null and retired_at is not null and replaced_by is not null) or
 (state<>'RETIRED' and retired_by is null and retired_at is null and replaced_by is null)),
 check((kind='SETUP' and jsonb_typeof(payload->'components')='array' and jsonb_array_length(payload->'components')<=9) or
 (kind='JOURNAL' and payload->>'category' in ('CONTRIBUTION','DISTRIBUTION','TRANSFER','EARNINGS_TRANSFER','OCI','ADJUSTMENT','UNCLASSIFIED')))
);
create unique index gl_equity_reporting_current on gl_equity_reporting(kind,target_id) where state='APPROVED';
create unique index gl_equity_reporting_pending on gl_equity_reporting(kind,target_id) where state='PENDING';
create index gl_equity_reporting_history on gl_equity_reporting(kind,target_id,id desc);
create function fcms_gl_equity_reporting_guard() returns trigger language plpgsql as $$
declare current_id bigint; component jsonb; account jsonb; seen bigint[]='{}'; names text[]='{}'; retained integer=0; category text;
begin
 if TG_OP='DELETE' then raise exception 'Equity reporting evidence is retained' using errcode='23514'; end if;
 perform pg_advisory_xact_lock(hashtextextended('fcms-equity/'||new.kind||'/'||new.target_id,0));
 if TG_OP='INSERT' then
  if new.state<>'PENDING' or new.version<>0 then raise exception 'Independent reporting review is required' using errcode='23514'; end if;
  select id into current_id from gl_equity_reporting where kind=new.kind and target_id=new.target_id and state='APPROVED';
  if new.base_id is distinct from current_id then raise exception 'Reporting base changed' using errcode='23514'; end if;
 else
  if row(new.id,new.kind,new.target_id,new.base_id,new.payload,new.reason,new.maker_id,new.request_key,new.payload_hash,new.created_at)
    is distinct from row(old.id,old.kind,old.target_id,old.base_id,old.payload,old.reason,old.maker_id,old.request_key,old.payload_hash,old.created_at)
  then raise exception 'Reporting proposal content is immutable' using errcode='23514'; end if;
  if new.version<>old.version+1 then raise exception 'Reporting version must advance once' using errcode='23514'; end if;
  if old.state='PENDING' then
   if new.state not in ('APPROVED','REJECTED','CANCELLED') then raise exception 'Invalid reporting decision' using errcode='23514'; end if;
  elsif old.state='APPROVED' then
   if new.state<>'RETIRED' or row(new.checker_id,new.reviewed_at,new.review_reason) is distinct from row(old.checker_id,old.reviewed_at,old.review_reason)
   then raise exception 'Approved evidence can only be superseded' using errcode='23514'; end if;
  else raise exception 'Reporting decisions are immutable' using errcode='23514'; end if;
 end if;
 if new.kind='JOURNAL' and (TG_OP='INSERT' or new.state='APPROVED') then
  if not exists(select 1 from gl_journals j where j.id=new.target_id and j.state='POSTED' and j.kind<>'OPENING' and j.reverses_id is null
     and exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=j.id and a.classification='EQUITY'))
  then raise exception 'Original posted equity journal is required' using errcode='23514'; end if;
  category=new.payload->>'category';
  if category is null or category not in ('CONTRIBUTION','DISTRIBUTION','TRANSFER','EARNINGS_TRANSFER','OCI','ADJUSTMENT','UNCLASSIFIED') then raise exception 'Invalid equity category' using errcode='23514'; end if;
  if category in ('CONTRIBUTION','DISTRIBUTION','OCI') and exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.target_id and a.classification in ('INCOME','EXPENSE'))
     or category='TRANSFER' and exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.target_id and a.classification<>'EQUITY')
     or category='EARNINGS_TRANSFER' and (not exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.target_id and a.classification in ('INCOME','EXPENSE')) or exists(select 1 from gl_lines l join gl_accounts a on a.id=l.account_id where l.journal_id=new.target_id and a.classification not in ('EQUITY','INCOME','EXPENSE')))
  then raise exception 'Equity category does not match posted journal membership' using errcode='23514'; end if;
 end if;
 if new.kind='SETUP' and (TG_OP='INSERT' or new.state='APPROVED') then
  if jsonb_typeof(new.payload->'components') is distinct from 'array' or jsonb_array_length(new.payload->'components')>9 then raise exception 'Invalid equity components' using errcode='23514'; end if;
  for component in select * from jsonb_array_elements(new.payload->'components') loop
   if coalesce(length(btrim(component->>'name')),0)=0 or length(component->>'name')>100 or length(component->>'nameSw')>100 or (component->>'name')~'[[:cntrl:]]' or (component->>'nameSw')~'[[:cntrl:]]' or lower(btrim(component->>'name'))=any(names)
      or jsonb_typeof(component->'accounts') is distinct from 'array' or jsonb_array_length(component->'accounts')=0 or jsonb_typeof(component->'retained') is distinct from 'boolean'
   then raise exception 'Invalid equity component' using errcode='23514'; end if;
   names=array_append(names,lower(btrim(component->>'name')));
   if (component->>'retained')::boolean then retained=retained+1; end if;
   for account in select * from jsonb_array_elements(component->'accounts') loop
    if jsonb_typeof(account)<>'number' or (account::text)::bigint=any(seen) or not exists(select 1 from gl_accounts where id=(account::text)::bigint and depth=4 and classification='EQUITY') then raise exception 'Use each equity posting account once' using errcode='23514'; end if;
    seen=array_append(seen,(account::text)::bigint);
   end loop;
  end loop;
  if retained>1 or (jsonb_array_length(new.payload->'components')+(case when retained=0 then 1 else 0 end)+(case when exists(select 1 from gl_accounts where depth=4 and classification='EQUITY' and not(id=any(seen))) then 1 else 0 end))>10
  then raise exception 'Too many equity components' using errcode='23514'; end if;
 end if;
 if TG_OP='UPDATE' and new.state='APPROVED' then
  if new.base_id is null then
   if exists(select 1 from gl_equity_reporting where kind=new.kind and target_id=new.target_id and state in ('APPROVED','RETIRED')) then raise exception 'Reporting base changed' using errcode='23514'; end if;
  elsif not exists(select 1 from gl_equity_reporting b where b.id=new.base_id and b.kind=new.kind and b.target_id=new.target_id and b.state='RETIRED' and b.replaced_by=new.id and b.retired_by=new.checker_id and b.retired_at=new.reviewed_at)
  then raise exception 'Reviewed replacement is required' using errcode='23514'; end if;
 end if;
 return new;
end; $$;
create trigger gl_equity_reporting_guard before insert or update or delete on gl_equity_reporting for each row execute function fcms_gl_equity_reporting_guard();
create function fcms_gl_equity_reporting_replacement_guard() returns trigger language plpgsql as $$
begin
 if not exists(select 1 from gl_equity_reporting r where r.id=new.replaced_by and r.kind=new.kind and r.target_id=new.target_id and r.base_id=new.id and r.state in ('APPROVED','RETIRED') and r.checker_id=new.retired_by and r.reviewed_at=new.retired_at)
 then raise exception 'Retirement requires an approved replacement' using errcode='23514'; end if;
 return null;
end; $$;
create constraint trigger gl_equity_reporting_replacement_guard after update on gl_equity_reporting deferrable initially deferred
 for each row when(new.state='RETIRED' and old.state='APPROVED') execute function fcms_gl_equity_reporting_replacement_guard();
