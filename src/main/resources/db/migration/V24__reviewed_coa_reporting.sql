-- Reviewed COA reporting definitions. No balances, account identities or postings are changed.
create table gl_account_reporting (
 id bigint generated by default as identity primary key,
 account_id bigint not null references gl_accounts(id), account_version bigint not null check(account_version>=0),
 base_id bigint references gl_account_reporting(id),
 section varchar(30) not null default '' check(section in ('','CURRENT_ASSETS','NON_CURRENT_ASSETS','CURRENT_LIABILITIES','NON_CURRENT_LIABILITIES','UNCLASSIFIED')),
 note_no integer check(note_no between 0 and 999), note_text varchar(2000) not null default '',
 reason varchar(500) not null check(length(btrim(reason))>0),
 state varchar(10) not null default 'PENDING' check(state in ('PENDING','APPROVED','REJECTED','CANCELLED','RETIRED')),
 maker_id bigint not null references users(id), checker_id bigint references users(id),
 request_key uuid not null, payload_hash varchar(64) not null check(payload_hash~'^[a-f0-9]{64}$'),
 version bigint not null default 0 check(version>=0),
 created_at timestamptz not null default current_timestamp, reviewed_at timestamptz,
 review_reason varchar(500) not null default '',
 retired_by bigint references users(id), retired_at timestamptz, replaced_by bigint references gl_account_reporting(id),
 unique(maker_id,request_key),
 check(base_id is null or base_id<id), check(replaced_by is null or replaced_by>id),
 check((note_no is not null and note_no>0) or note_text=''),
 check(regexp_replace(note_text,E'[\\n\\r]','','g')!~'[[:cntrl:]]'),
 check((state='PENDING' and checker_id is null and reviewed_at is null and review_reason='') or
       (state<>'PENDING' and checker_id is not null and reviewed_at is not null and length(btrim(review_reason))>0)),
 check(state not in ('APPROVED','REJECTED','RETIRED') or checker_id<>maker_id),
 check(state<>'CANCELLED' or checker_id=maker_id),
 check((state='RETIRED' and retired_by is not null and retired_at is not null and replaced_by is not null) or
       (state<>'RETIRED' and retired_by is null and retired_at is null and replaced_by is null))
);
create unique index gl_reporting_current on gl_account_reporting(account_id) where state='APPROVED';
create unique index gl_reporting_pending on gl_account_reporting(account_id) where state='PENDING';
create index gl_reporting_account_history on gl_account_reporting(account_id,id desc);
create function fcms_gl_reporting_guard() returns trigger language plpgsql as $$
declare a gl_accounts; current_id bigint;
begin
 if TG_OP='DELETE' then raise exception 'Reporting definitions are retained as evidence' using errcode='23514'; end if;
 if TG_OP='INSERT' then
  if new.state<>'PENDING' or new.version<>0 then raise exception 'Reporting definitions start pending independent review' using errcode='23514'; end if;
 else
  if row(new.id,new.account_id,new.account_version,new.base_id,new.section,new.note_no,new.note_text,new.reason,new.maker_id,new.request_key,new.payload_hash,new.created_at)
     is distinct from row(old.id,old.account_id,old.account_version,old.base_id,old.section,old.note_no,old.note_text,old.reason,old.maker_id,old.request_key,old.payload_hash,old.created_at)
  then raise exception 'Reporting proposal content is immutable' using errcode='23514'; end if;
  if new.version<>old.version+1 then raise exception 'Reporting revision must advance once' using errcode='23514'; end if;
  if old.state='PENDING' then
   if new.state not in ('APPROVED','REJECTED','CANCELLED') then raise exception 'Invalid reporting decision' using errcode='23514'; end if;
  elsif old.state='APPROVED' then
   if new.state<>'RETIRED' or row(new.checker_id,new.reviewed_at,new.review_reason) is distinct from row(old.checker_id,old.reviewed_at,old.review_reason)
   then raise exception 'Approved reporting evidence can only be superseded' using errcode='23514'; end if;
  else raise exception 'Reporting decision history is immutable' using errcode='23514';
  end if;
 end if;
 -- Match the application lock order: account, then its immutable proposal.
 select * into a from gl_accounts where id=new.account_id for update;
 if TG_OP='INSERT' or new.state='APPROVED' then
  if a.id is null or not a.active or a.version<>new.account_version then raise exception 'Active unchanged account is required' using errcode='23514'; end if;
  if new.section<>'' and (a.depth<>2 or a.classification not in ('ASSET','LIABILITY') or
       a.classification='ASSET' and new.section not in ('CURRENT_ASSETS','NON_CURRENT_ASSETS','UNCLASSIFIED') or
       a.classification='LIABILITY' and new.section not in ('CURRENT_LIABILITIES','NON_CURRENT_LIABILITIES','UNCLASSIFIED'))
  then raise exception 'Reporting section requires the matching actual subgroup' using errcode='23514'; end if;
 end if;
 if TG_OP='INSERT' then
  select id into current_id from gl_account_reporting where account_id=new.account_id and state='APPROVED';
  if new.base_id is distinct from current_id then raise exception 'Reporting base changed' using errcode='23514'; end if;
 elsif new.state='APPROVED' then
  if new.base_id is null then
   if exists(select 1 from gl_account_reporting where account_id=new.account_id and state in ('APPROVED','RETIRED'))
   then raise exception 'Reporting base changed' using errcode='23514'; end if;
  elsif not exists(select 1 from gl_account_reporting where id=new.base_id and account_id=new.account_id and state='RETIRED' and replaced_by=new.id and retired_by=new.checker_id and retired_at=new.reviewed_at)
  then raise exception 'Reporting replacement must retain its reviewed base' using errcode='23514'; end if;
 end if;
 return new;
end; $$;
create trigger gl_reporting_guard before insert or update or delete on gl_account_reporting for each row execute function fcms_gl_reporting_guard();

-- A replacement and retirement must commit together; retaining a pending replacement is insufficient.
create function fcms_gl_reporting_replacement_guard() returns trigger language plpgsql as $$
begin
 if not exists(select 1 from gl_account_reporting r where r.id=new.replaced_by and r.account_id=new.account_id
                and r.base_id=new.id and r.state in ('APPROVED','RETIRED') and r.checker_id=new.retired_by and r.reviewed_at=new.retired_at)
 then raise exception 'Reporting retirement requires its approved replacement' using errcode='23514'; end if;
 return null;
end; $$;
create constraint trigger gl_reporting_replacement_guard after update on gl_account_reporting
 deferrable initially deferred for each row when(new.state='RETIRED' and old.state='APPROVED')
 execute function fcms_gl_reporting_replacement_guard();

-- Actual ancestor IDs, not account codes or names, define family membership and inheritance.
create view gl_report_account_settings as
select a.id account_id,p.id group_id,p.code group_code,p.name group_name,
 case when a.classification in ('INCOME','EXPENSE','EQUITY') then a.classification else coalesce(nullif(gv.section,''),'UNCLASSIFIED') end section,
 coalesce(av.note_no,pv.note_no,gv.note_no,rv.note_no,0) note_no,
 case when av.note_no is not null then av.note_text when pv.note_no is not null then pv.note_text
      when gv.note_no is not null then gv.note_text when rv.note_no is not null then rv.note_text else '' end note_text,
 av.id leaf_version_id,pv.id family_version_id,gv.id subgroup_version_id,rv.id root_version_id,
 gv.id section_version_id,
 case when av.note_no is not null then av.id when pv.note_no is not null then pv.id when gv.note_no is not null then gv.id when rv.note_no is not null then rv.id end note_version_id
from gl_accounts a
left join gl_accounts p on p.id=a.parent_id and p.depth=3 and p.classification=a.classification
left join gl_accounts g on g.id=p.parent_id and g.depth=2 and g.classification=a.classification
left join gl_accounts r on r.id=g.parent_id and r.depth=1 and r.classification=a.classification
left join gl_account_reporting av on av.account_id=a.id and av.state='APPROVED'
left join gl_account_reporting pv on pv.account_id=p.id and pv.state='APPROVED'
left join gl_account_reporting gv on gv.account_id=g.id and gv.state='APPROVED'
left join gl_account_reporting rv on rv.account_id=r.id and rv.state='APPROVED'
where a.depth=4;
