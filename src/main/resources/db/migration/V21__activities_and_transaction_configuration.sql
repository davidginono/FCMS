-- Transaction configuration replaces the standalone mapping workspace. No journal is rewritten.
create table gl_activities (
 id bigint generated by default as identity primary key,
 code varchar(40) not null unique check(code~'^[A-Z0-9][A-Z0-9_.-]{0,39}$'),
 name varchar(160) not null check(length(trim(name))>0),
 description varchar(500) not null default '', active boolean not null default true,
 version bigint not null default 0, created_by bigint references users(id),
 request_key uuid, payload_hash varchar(64), created_at timestamptz not null default current_timestamp,
 unique(created_by,request_key),
 check((created_by is null and request_key is null and payload_hash is null) or
  (created_by is not null and request_key is not null and payload_hash is not null and payload_hash ~ '^[0-9a-f]{64}$'))
);
insert into gl_activities(code,name) values ('INCOME','Other income'),('PETTY','Petty cash'),
 ('CLOUD','Cloud backup'),('BULK','Bulk SMS'),('EXPENSE','Expenses');
create table gl_transactions (
 id bigint generated by default as identity primary key,
 activity_id bigint not null references gl_activities(id),
 code varchar(40) not null unique check(code~'^[A-Z0-9][A-Z0-9_.-]{0,39}$'),
 name varchar(160) not null check(length(trim(name))>0), description varchar(500) not null default '',
 source_event varchar(30) not null check(source_event in ('INCOME_IN','PETTY_IN','PETTY_OUT','CLOUD_IN','CLOUD_OUT','BULK_IN','BULK_OUT','EXPENSE_PAYMENT','INCOME_OPENING_REVERSAL','PETTY_OPENING_REVERSAL','CLOUD_OPENING_REVERSAL','BULK_OPENING_REVERSAL','EXPENSE_OPENING_REVERSAL')),
 active boolean not null default true, version bigint not null default 0,
 created_by bigint references users(id), request_key uuid, payload_hash varchar(64),
 created_at timestamptz not null default current_timestamp, unique(created_by,request_key),
 check((created_by is null and request_key is null and payload_hash is null) or
  (created_by is not null and request_key is not null and payload_hash is not null and payload_hash ~ '^[0-9a-f]{64}$'))
);
insert into gl_transactions(activity_id,code,name,source_event)
select a.id,e.code,e.name,e.code from (values
 ('INCOME','INCOME_IN','Income received'),('PETTY','PETTY_IN','Petty cash received'),
 ('PETTY','PETTY_OUT','Petty cash paid'),('CLOUD','CLOUD_IN','Cloud backup received'),
 ('CLOUD','CLOUD_OUT','Cloud backup paid'),('BULK','BULK_IN','Bulk SMS received'),
 ('BULK','BULK_OUT','Bulk SMS paid'),('EXPENSE','EXPENSE_PAYMENT','Expense paid'),
 ('INCOME','INCOME_OPENING_REVERSAL','Opening income reversal'),
 ('PETTY','PETTY_OPENING_REVERSAL','Opening petty cash reversal'),
 ('CLOUD','CLOUD_OPENING_REVERSAL','Opening cloud backup reversal'),
 ('BULK','BULK_OPENING_REVERSAL','Opening bulk SMS reversal'),
 ('EXPENSE','EXPENSE_OPENING_REVERSAL','Opening expense reversal')
) e(activity,code,name) join gl_activities a on a.code=e.activity;
create index gl_transactions_activity_code on gl_transactions(activity_id,code,id);
create index gl_transactions_event on gl_transactions(source_event,id) where active;
alter table gl_posting_mappings add column transaction_id bigint references gl_transactions(id);
create or replace function fcms_gl_mapping_guard() returns trigger language plpgsql as $$
declare d gl_accounts; c gl_accounts; delta integer; has_cash boolean;
begin
 if TG_OP='UPDATE' and old.transaction_id is null and new.transaction_id is not null
  and (to_jsonb(new)-'transaction_id')=(to_jsonb(old)-'transaction_id') then return new; end if;
 if TG_OP='DELETE' then raise exception 'Posting mappings are retained as accounting evidence' using errcode='23514'; end if;
 if TG_OP='INSERT' then
  if new.state<>'PENDING' or new.version<>0 then raise exception 'Mappings start pending independent review' using errcode='23514'; end if;
 else
  if row(new.transaction_id,new.source_event,new.debit_account_id,new.credit_account_id,new.voucher_kind,new.cash_flow,new.policy_reference,new.maker_id,new.request_key,new.payload_hash,new.created_at)
   is distinct from row(old.transaction_id,old.source_event,old.debit_account_id,old.credit_account_id,old.voucher_kind,old.cash_flow,old.policy_reference,old.maker_id,old.request_key,old.payload_hash,old.created_at)
  then raise exception 'Mapping revisions are immutable' using errcode='23514'; end if;
  if new.version<>old.version+1 then raise exception 'Mapping version must advance once' using errcode='23514'; end if;
  if old.state='PENDING' then
   if new.state not in ('APPROVED','REJECTED','CANCELLED') or (new.state='CANCELLED' and new.checker_id<>new.maker_id)
   then raise exception 'Invalid mapping review transition' using errcode='23514'; end if;
  elsif old.state='APPROVED' then
   if new.state<>'RETIRED' or row(new.checker_id,new.review_reason,new.reviewed_at) is distinct from row(old.checker_id,old.review_reason,old.reviewed_at)
   then raise exception 'An approved mapping can only be retired with its evidence retained' using errcode='23514'; end if;
  else raise exception 'Reviewed mapping history is immutable' using errcode='23514';
  end if;
 end if;
 if TG_OP='INSERT' or new.state='APPROVED' then
  -- Consistent account lock order matches voucher posting.
  perform id from gl_accounts where id in (new.debit_account_id,new.credit_account_id) order by id for share;
  select * into d from gl_accounts where id=new.debit_account_id;
  select * into c from gl_accounts where id=new.credit_account_id;
  if d.id is null or c.id is null or not d.active or not c.active or d.depth<>4 or c.depth<>4
  then raise exception 'Active posting accounts are required' using errcode='23514'; end if;
  delta := (case when d.cash_account then 1 else 0 end)-(case when c.cash_account then 1 else 0 end);
  has_cash := d.cash_account or c.cash_account;
  if (new.voucher_kind='RECEIPT' and delta<=0) or (new.voucher_kind='PAYMENT' and delta>=0)
  then raise exception 'Voucher cash direction does not match the accounts' using errcode='23514'; end if;
  if (delta<>0 and new.cash_flow not in ('OPERATING','INVESTING','FINANCING')) or
   (delta=0 and new.cash_flow<>case when has_cash then 'INTERNAL' else 'NONE' end)
  then raise exception 'Cash-flow classification must match the account pair' using errcode='23514'; end if;
 end if;
 return new;
end; $$;

