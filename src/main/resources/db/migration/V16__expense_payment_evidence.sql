create function fcms_expense_state_guard() returns trigger language plpgsql as $$
declare before_state text; after_state text;
begin
 if TG_OP='DELETE' then raise exception 'Expense history cannot be deleted' using errcode='23514'; end if;
 select name into after_state from expense_status where id=new.status_id;
 if TG_OP='INSERT' then
  if after_state<>'draft' then raise exception 'Expenses start as drafts' using errcode='23514'; end if;
  return new;
 end if;
 select name into before_state from expense_status where id=old.status_id;
 if new.user_id<>old.user_id then raise exception 'Expense ownership is immutable' using errcode='23514'; end if;
 if before_state in ('approved','paid','reversed') and row(new.date_created,new.category,new.description,new.payee,new.amount,new.financial_year,new.approved_by) is distinct from row(old.date_created,old.category,old.description,old.payee,old.amount,old.financial_year,old.approved_by)
 then raise exception 'Approved monetary evidence is immutable' using errcode='23514'; end if;
 if before_state in ('paid','reversed') and row(new.payment_reference,new.paid_at,new.paid_on,new.paid_by) is distinct from row(old.payment_reference,old.paid_at,old.paid_on,old.paid_by)
 then raise exception 'Payment evidence is immutable' using errcode='23514'; end if;
 if after_state<>before_state and not ((before_state='draft' and after_state='submitted') or (before_state='rejected' and after_state in ('draft','submitted')) or (before_state='submitted' and after_state in ('approved','rejected')) or (before_state='approved' and after_state='paid') or (before_state='paid' and after_state='reversed'))
 then raise exception 'Invalid expense transition' using errcode='23514'; end if;
 if after_state='approved' and (new.approved_by is null or new.approved_by=new.user_id)
 then raise exception 'Independent approval is required' using errcode='23514'; end if;
 if after_state='paid' and (new.approved_by is null or new.paid_by is null or new.paid_at is null or new.paid_on is null or length(trim(new.payment_reference))=0)
 then raise exception 'Complete payment evidence is required' using errcode='23514'; end if;
 if after_state='reversed' and not exists(select 1 from expense_reversals r where r.expense_id=new.id and r.actor_id<>new.user_id)
 then raise exception 'Independent reversal evidence is required' using errcode='23514'; end if;
 return new;
end; $$;
create trigger expense_state_guard before insert or update or delete on expenses for each row execute function fcms_expense_state_guard();
