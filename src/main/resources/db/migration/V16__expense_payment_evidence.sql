alter table expenses add column paid_at timestamptz, add column paid_on date, add column paid_by bigint references users(id);
-- Recover only dates and actors supported by retained payment audit evidence.
with payment as (
 select distinct on(resource_id) resource_id,actor_id,occurred_at from audit_events
 where resource='expenses' and action='expense.pay' order by resource_id,id
) update expenses e set paid_at=p.occurred_at,paid_on=(p.occurred_at at time zone 'Africa/Dar_es_Salaam')::date,paid_by=p.actor_id
 from payment p where e.id=p.resource_id;
create table expense_events (
 id bigint generated by default as identity primary key, expense_id bigint not null references expenses(id),
 action varchar(20) not null, from_status varchar(30) not null, to_status varchar(30) not null,
 actor_id bigint not null references users(id), reason varchar(1000) not null,
 payment_reference varchar(100) not null, amount numeric(14,2) not null, category varchar(100) not null, payee varchar(255) not null, version bigint not null, occurred_at timestamptz not null default current_timestamp,
 unique(expense_id,version)
);
create trigger expense_events_immutable before update or delete on expense_events for each row execute function fcms_gl_evidence_guard();
